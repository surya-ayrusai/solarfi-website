  function pickVoice() {
    if (!synth) return null;
    var voices = synth.getVoices() || [];
    if (!voices.length) return null;
    var rank = function (v) {
      var lang = (v.lang || '').replace('_', '-').toLowerCase();
      var name = v.name || '';
      var r = 0;
      if (lang === 'en-in') r += 0; else if (lang.indexOf('en') === 0) r += 10; else r += 100;
      if (/premium/i.test(name)) r += 0;
      else if (/enhanced/i.test(name)) r += 1;
      else if (/(natural|neural)/i.test(name)) r += 2;
      else if (/(google|online)/i.test(name)) r += 3;
      else r += 5;
      return r;
    };
    var best = voices.slice().sort(function (a, b) { return rank(a) - rank(b); })[0];
    return best && (best.lang || '').toLowerCase().indexOf('en') === 0 ? best : null;
  }

  function chunks(text) {
    // Chrome stops long utterances after ~15 s, so speak sentence by sentence.
    // split after . ! ? followed by a space (keeps decimals such as 3.2 intact)
    var parts = text.replace(/([.!?])\s+/g, '$1\u0001').split('\u0001').map(function (p) { return p.trim(); }).filter(Boolean);
    var out = [];
    parts.forEach(function (p) {
      if (out.length && (out[out.length - 1] + ' ' + p).length < 160) out[out.length - 1] += ' ' + p;
      else out.push(p);
    });
    return out;
  }

  function speakable(text) {
    return text.replace(/MPPT/g, 'M P P T').replace(/APSPDCL/g, 'A P S P D C L');
  }

  // Speak text; call onDone once when the LAST chunk has really finished.
  function speak(text, gen, onDone) {
    var voice = pickVoice();
    var list = chunks(speakable(text));
    var finished = false;
    var watchdog = null;
    var finish = function (ok) {
      if (watchdog) clearTimeout(watchdog);
      if (finished || gen !== state.gen) return;
      finished = true;
      state.utts = [];
      onDone(ok);
    };
    state.utts = [];
    // Safety net only: if a browser never reports the end of speech, move on
    // well after the words should have finished.
    watchdog = setTimeout(function () { finish(true); }, readingTime(text) * 2.5 + 4000);
    list.forEach(function (c, i) {
      var u = new SpeechSynthesisUtterance(c);
      if (voice) { u.voice = voice; u.lang = voice.lang; } else { u.lang = 'en-IN'; }
      u.rate = 0.95;
      u.pitch = 1;
      if (i === list.length - 1) {
        u.onend = function () { finish(true); };
      }
      u.onerror = function (e) {
        if (u.sfStopped || gen !== state.gen) return; // we cancelled it ourselves
        if (e && (e.error === 'interrupted' || e.error === 'canceled')) {
          // something else on the page (e.g. the chat assistant) took over the voice
          if (watchdog) clearTimeout(watchdog);
          finished = true;
          pause();
          return;
        }
        finish(false);
      };
      state.utts.push(u);
      synth.speak(u);
    });
  }

  // Only cancel speech the guide started (the chat assistant may be talking).
  function stopVoice() {
    if (!synth || !state.utts.length) return;
    state.utts.forEach(function (u) { u.sfStopped = true; });
    state.utts = [];
    try { synth.cancel(); } catch (e) { /* ignore */ }
  }

  /* ------------------------------------------------------------------ */
  /* Guided narration controller                                         */
  /* ------------------------------------------------------------------ */
  function clearTimer() { if (state.timer) { clearTimeout(state.timer); state.timer = null; } }

  function readingTime(text) {
    // used only when muted or speech is unavailable
    var words = text.split(/\s+/).length;
    return Math.max(3500, words * 380 + 1200);
  }

  function runStep(i) {
    var cfg = SCENARIOS[state.scene];
    clearTimer();
    stopVoice();
    state.gen += 1;
    var gen = state.gen;
    state.step = i;
    state.mode = 'playing';
    var step = cfg.steps[i];
    var text = fill(step.text, state.values);
    highlight(step.targets);
    renderGuide(text);

    var next = function () {
      if (gen !== state.gen) return;
      if (i + 1 < cfg.steps.length) {
        // short natural pause between steps
        state.timer = setTimeout(function () { if (gen === state.gen) runStep(i + 1); }, 550);
      } else {
        finishGuide();
      }
    };

    if (!state.muted && synth) {
      speak(text, gen, function (ok) {
        if (!ok) {
          note('Voice isn\'t available right now, so the guide will continue silently.');
          state.timer = setTimeout(next, readingTime(text));
          return;
        }
        next();
      });
    } else {
      state.timer = setTimeout(next, readingTime(text));
    }
  }

  function finishGuide() {
    clearTimer();
    state.mode = 'done';
    highlight(null);
    renderGuide('That completes the ' + SCENARIOS[state.scene].title + ' walkthrough. Replay it, or choose another scenario above.');
  }

  function pause() {
    if (state.mode !== 'playing') return;
    state.gen += 1;          // ignore callbacks from the speech we cancel
    clearTimer();
    stopVoice();
    state.mode = 'paused';
    renderGuide();
  }

  function resume() {
    if (state.mode === 'paused') runStep(Math.max(0, state.step)); // restart the current step cleanly
  }

  function play() {
    if (state.mode === 'playing') return pause();
    if (state.mode === 'paused') return resume();
    runStep(0); // idle or done
  }

  function replay() { runStep(0); }

  function go(delta) {
    var n = SCENARIOS[state.scene].steps.length;
    var target = Math.min(n - 1, Math.max(0, (state.step < 0 ? 0 : state.step) + delta));
    if (state.mode === 'playing') runStep(target);
    else {
      // move without speaking while paused/idle
      state.gen += 1;
      clearTimer();
      stopVoice();
      state.step = target;
      state.mode = 'paused';
      highlight(SCENARIOS[state.scene].steps[target].targets);
      renderGuide();
    }
  }

  function toggleMute() {
    state.muted = !state.muted;
    try { localStorage.setItem('solarfi-guide-muted', state.muted ? '1' : '0'); } catch (e) { /* ignore */ }
    if (state.mode === 'playing') runStep(state.step); // continue the same step, with or without voice
    else renderGuide();
  }

  function selectScene(id, opts) {
    if (!SCENARIOS[id]) return;
    clearTimer();
    stopVoice();
    state.gen += 1;
    state.scene = id;
    state.values = derive(SCENARIOS[id]);
    state.step = -1;
    state.mode = 'idle';
    if (synth) note('');
    highlight(null);
    renderAll();
    renderGuide();
    if (opts && opts.narrate) runStep(0);
  }

